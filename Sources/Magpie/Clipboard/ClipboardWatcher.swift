import AppKit

enum ClipboardChangeOrigin: Sendable, Equatable {
    case observed
    case explicitScreenshot
}

/// Sendable pasteboard snapshot captured on the main thread.
///
/// AppKit pasteboard objects are not a good boundary to hand to background
/// work. The watcher copies out only the data Magpie needs, then detection and
/// storage can run without holding the main run loop.
struct ClipboardSnapshot: Sendable {
    let changeCount: Int
    let typeNames: [String]
    let fileURLs: [URL]
    let imageData: Data?
    let imageTypeName: String?
    let string: String?

    // Presence is authoritative; marker data may be empty. This protection is
    // independent of the optional heuristic filter.
    var isPrivate: Bool { Self.isPrivate(typeNames: typeNames) }

    static func isPrivate(typeNames: [String]) -> Bool {
        let excluded: Set<String> = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
            "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping"
        ]
        return !excluded.isDisjoint(with: typeNames)
    }

    @MainActor
    static func capture(from pasteboard: NSPasteboard) -> ClipboardSnapshot {
        let count = pasteboard.changeCount
        // Inspect all items before asking providers for any content.
        let typeNames = Array(Set((pasteboard.types ?? []).map(\.rawValue)
            + (pasteboard.pasteboardItems ?? []).flatMap { $0.types.map(\.rawValue) }))
        guard !isPrivate(typeNames: typeNames) else {
            return ClipboardSnapshot(changeCount: count, typeNames: typeNames,
                fileURLs: [], imageData: nil, imageTypeName: nil, string: nil)
        }
        let types = pasteboard.types ?? []
        let hasFileURL = types.contains(.fileURL)
        let fileURLs = hasFileURL
            ? (pasteboard.readObjects(forClasses: [NSURL.self]) as? [URL] ?? [])
            : []
        let imageType = pasteboard.availableType(from: [.png, .tiff])
        let imageData = imageType.flatMap { pasteboard.data(forType: $0) }

        let string = pasteboard.string(forType: .string)
        // NSPasteboard is not an atomic read: fail closed if ownership changed.
        guard pasteboard.changeCount == count else {
            return ClipboardSnapshot(changeCount: count,
                typeNames: ["org.nspasteboard.TransientType"], fileURLs: [],
                imageData: nil, imageTypeName: nil, string: nil)
        }
        return ClipboardSnapshot(
            changeCount: count,
            typeNames: typeNames,
            fileURLs: fileURLs,
            imageData: imageData,
            imageTypeName: imageType?.rawValue,
            string: string
        )
    }
}

/// Polls NSPasteboard.changeCount on a 400 ms cadence and fires `onChange`
/// when the count moves. Initial pasteboard state is treated as already-seen
/// so we don't dump existing user content into history at launch.
@MainActor
final class ClipboardWatcher {
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?
    private var preparedOrigin: ClipboardChangeOrigin?
    private let pollInterval: TimeInterval

    /// Fired on the main thread whenever the pasteboard changes.
    /// The closure receives a copied snapshot; expensive ingest work should
    /// continue off the main thread.
    var onChange: ((ClipboardSnapshot, ClipboardChangeOrigin) -> Void)?
    /// Checked before content reads, including explicit screenshot ingestion.
    var allowsCapture: () -> Bool = { true }

    func discardPendingChanges() {
        lastChangeCount = pasteboard.changeCount
        preparedOrigin = nil
    }

    init(pasteboard: NSPasteboard = .general, pollInterval: TimeInterval = 0.4) {
        self.pasteboard = pasteboard
        self.pollInterval = pollInterval
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let t = Timer.scheduledTimer(withTimeInterval: pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.pollOnce()
            }
        }
        t.tolerance = pollInterval * 0.1
        // RunLoop.main is the default; explicit add keeps the timer alive during modal panels.
        RunLoop.main.add(t, forMode: .common)
        self.timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Reserve the next image pasteboard change immediately before an explicit
    /// image write. Cancel the reservation if that write fails.
    func prepareNextChange(origin: ClipboardChangeOrigin) {
        preparedOrigin = origin
    }

    func cancelPreparedChange(origin: ClipboardChangeOrigin) {
        guard preparedOrigin == origin else { return }
        preparedOrigin = nil
    }

    /// Immediately processes a pasteboard change and advances lastChangeCount,
    /// preventing the regular timer from ingesting the same screenshot twice.
    @discardableResult
    func pollNow() -> Bool {
        pollOnce()
    }

    @discardableResult
    func pollNow(origin: ClipboardChangeOrigin) -> Bool {
        pollOnce(forcedOrigin: origin)
    }

    @discardableResult
    private func pollOnce(forcedOrigin: ClipboardChangeOrigin? = nil) -> Bool {
        guard allowsCapture() else {
            discardPendingChanges()
            return false
        }
        let current = pasteboard.changeCount
        guard current != lastChangeCount else {
            if let forcedOrigin, preparedOrigin == forcedOrigin {
                preparedOrigin = nil
            }
            return false
        }
        lastChangeCount = current
        let snapshot = ClipboardSnapshot.capture(from: pasteboard)
        guard !snapshot.isPrivate else {
            preparedOrigin = nil
            return false
        }

        let origin: ClipboardChangeOrigin
        if let forcedOrigin {
            origin = forcedOrigin
            if preparedOrigin == forcedOrigin {
                preparedOrigin = nil
            }
        } else if let preparedOrigin {
            guard let imageData = snapshot.imageData, !imageData.isEmpty else {
                // A reservation only applies to images; wait for the explicit
                // writer to finish or cancel it.
                NSLog("[clipboard]")
                return false
            }
            origin = preparedOrigin
            self.preparedOrigin = nil
        } else {
            origin = .observed
        }

        onChange?(snapshot, origin)
        return true
    }
}


/// A persisted deadline survives relaunch; expiration never imports paused copies.
/// Injected clock/defaults make sleep and restart behavior deterministic in tests.
@MainActor
final class ClipboardRecordingControl {
    private static let key = "magpie.recording.pausedUntil"
    private let defaults: UserDefaults
    private let now: () -> Date
    private(set) var pausedUntil: Date?
    var onChange: (() -> Void)?

    init(defaults: UserDefaults = .standard, now: @escaping () -> Date = Date.init) {
        self.defaults = defaults
        self.now = now
        let timestamp = defaults.double(forKey: Self.key)
        pausedUntil = timestamp > 0 ? Date(timeIntervalSince1970: timestamp) : nil
    }

    var isPaused: Bool {
        guard let deadline = pausedUntil else { return false }
        if deadline > now() { return true }
        resume()
        return false
    }

    func pause(for duration: TimeInterval) {
        guard duration.isFinite, duration > 0 else { return }
        let deadline = now().addingTimeInterval(duration)
        pausedUntil = deadline
        defaults.set(deadline.timeIntervalSince1970, forKey: Self.key)
        onChange?()
    }

    func resume() {
        guard pausedUntil != nil else { return }
        pausedUntil = nil
        defaults.removeObject(forKey: Self.key)
        onChange?()
    }
}
