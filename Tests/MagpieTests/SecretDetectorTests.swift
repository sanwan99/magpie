final class SecretDetectorTests: XCTestCase {

    // MARK: - Positive matches (should be detected as secret)

    func testApiKeyAssignmentEquals() {
        XCTAssertTrue(SecretDetector.looksSecret("api_key=abc123def456"))
    }

    func testApiKeyAssignmentColon() {
        XCTAssertTrue(SecretDetector.looksSecret("api_key: sk-1234567890abcdef"))
    }

    func testApiKeyDashedSpelling() {
        XCTAssertTrue(SecretDetector.looksSecret("api-key=xyz789"))
    }

    func testAccessKeyAssignment() {
        XCTAssertTrue(SecretDetector.looksSecret("access_key=ABCD1234"))
    }

    func testSecretKeyAssignment() {
        XCTAssertTrue(SecretDetector.looksSecret("secret_key=hunter2"))
    }

    func testTokenAssignment() {
        XCTAssertTrue(SecretDetector.looksSecret("token=xoxb-12345"))
    }

    func testPasswordAssignment() {
        XCTAssertTrue(SecretDetector.looksSecret("password = ChangeMe42!"))
    }

    func testBearerToken() {
        XCTAssertTrue(SecretDetector.looksSecret("bearer eyJhbGc.payload.signature"))
    }

    func testAuthorizationBearer() {
        XCTAssertTrue(SecretDetector.looksSecret("Authorization: Bearer abc123"))
    }

    func testJWT() {
        XCTAssertTrue(SecretDetector.looksSecret("eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.SflKxwRJSMeKKF2QT4fwpMeJf36POk6yJV_adQssw5c"))
    }

    func testGitHubClassicToken() {
        XCTAssertTrue(SecretDetector.looksSecret("ghp_ABCDEFGHIJKLMNOPQRSTUVWXYZabcdef"))
    }

    func testGitHubFineGrainedPAT() {
        XCTAssertTrue(SecretDetector.looksSecret("github_pat_ABCDEFGHIJKLMNOPQRSTUV_abcdefghijklmnopqrstuvwxyz0123456789ABCDEF"))
    }

    func testAWSAccessKey() {
        XCTAssertTrue(SecretDetector.looksSecret("AKIAIOSFODNN7EXAMPLE"))
    }

    func testOTP() {
        XCTAssertTrue(SecretDetector.looksSecret("Your verification code is 123456"))
    }

    func testOTPLowercase() {
        XCTAssertTrue(SecretDetector.looksSecret("otp 654321"))
    }

    // MARK: - Embedded in larger text

    func testEmbeddedInLogLine() {
        let line = "[2026-04-26 10:00:00] DEBUG api_key=mysecretvalue request id=42"
        XCTAssertTrue(SecretDetector.looksSecret(line))
    }

    func testEmbeddedInJSON() {
        let json = #"{"name": "alice", "api_key": "abcd-1234"}"#
        // The colon-form regex requires `api_key:` shape — JSON has it (key:value).
        XCTAssertTrue(SecretDetector.looksSecret(json))
    }

    // MARK: - Negative matches (should NOT be detected as secret)

    func testPlainSentence() {
        XCTAssertFalse(SecretDetector.looksSecret("Remember to bring your password manager tomorrow."))
    }

    func testWordContainingTokenAsSubstring() {
        // "tokens" alone shouldn't match — needs the `:= …` shape.
        XCTAssertFalse(SecretDetector.looksSecret("Two tokens of appreciation"))
    }

    func testCodeWithoutCredentials() {
        let code = """
        func add(a: Int, b: Int) -> Int {
            return a + b
        }
        """
        XCTAssertFalse(SecretDetector.looksSecret(code))
    }

    func testMarkdownLink() {
        let md = "[GitHub](https://github.com/sanwan99/magpie)"
        XCTAssertFalse(SecretDetector.looksSecret(md))
    }

    func testEmailNotASecret() {
        XCTAssertFalse(SecretDetector.looksSecret("contact: alice@example.com"))
    }

    func testShortAlphanumericNotJWT() {
        // "eyJ" prefix alone isn't enough — JWT regex requires three base64 segments.
        XCTAssertFalse(SecretDetector.looksSecret("eyJ.short"))
    }

    func testNonAKIAUppercaseString() {
        // 16 uppercase chars but not starting with AKIA — shouldn't match.
        XCTAssertFalse(SecretDetector.looksSecret("XYZAIOSFODNN7EXAMPLE"))
    }

    func testSixDigitsWithoutContext() {
        // 6 digits alone (no "code"/"otp" wording nearby) shouldn't match.
        XCTAssertFalse(SecretDetector.looksSecret("Order #123456 shipped"))
    }

    // MARK: - Empty / whitespace

    func testEmptyString() {
        XCTAssertFalse(SecretDetector.looksSecret(""))
    }

    func testWhitespaceOnly() {
        XCTAssertFalse(SecretDetector.looksSecret("   \n\t  "))
    }
}

@MainActor
final class ClipboardPrivacyTests: XCTestCase {
    func testPrivacyMarkersDiscardContentEvenWithHeuristicsDisabled() async throws {
        let db = Magpie.Database.makeInMemoryForTests()
        let ingest = ClipboardIngestor(repository: ClipRepository(database: db))
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            let pb = NSPasteboard.withUniqueName()
            defer { pb.releaseGlobally() }
            pb.declareTypes([.string, .init(marker)], owner: nil)
            pb.setString("private test value", forType: .string)
            pb.setData(Data(), forType: .init(marker))
            let snapshot = ClipboardSnapshot.capture(from: pb)
            XCTAssertTrue(snapshot.isPrivate)
            XCTAssertNil(snapshot.string)
            XCTAssertNil(snapshot.imageData)
            let changed = await ingest.ingest(snapshot: snapshot, policy: .init(
                appBundleIdentifier: nil, ignoredApps: [], skipSecretLooking: false))
            XCTAssertFalse(changed)
        }
        XCTAssertEqual(try ClipRepository(database: db).count(), 0)
        XCTAssertEqual(try db.dbQueue.read { try Int.fetchOne($0, sql: "SELECT COUNT(*) FROM clips_fts") }, 0)
    }

    func testSecretSnapshotAndIgnoredAppNeverReachDatabaseOrFTS() async throws {
        let db = Magpie.Database.makeInMemoryForTests()
        let ingest = ClipboardIngestor(repository: ClipRepository(database: db))
        for text in ["Authorization: Bearer synthetic-token", "验证码：123456", "normal text"] {
            let snapshot = ClipboardSnapshot(changeCount: 1, typeNames: ["public.utf8-plain-text"],
                fileURLs: [], imageData: nil, imageTypeName: nil, string: text)
            let changed = await ingest.ingest(snapshot: snapshot, policy: .init(
                appBundleIdentifier: text == "normal text" ? "ignored" : nil,
                ignoredApps: ["ignored"], skipSecretLooking: true))
            XCTAssertFalse(changed)
        }
        XCTAssertEqual(try ClipRepository(database: db).count(), 0)
        XCTAssertEqual(try db.dbQueue.read { try Int.fetchOne($0, sql: "SELECT COUNT(*) FROM clips_fts") }, 0)
    }

    func testMixedImageSecretAndFailedInsertLeaveNoFiles() async throws {
        let db = Magpie.Database.makeInMemoryForTests()
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        let data = try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
        let ingestor = ClipboardIngestor(repository: ClipRepository(database: db), imageDirectoryURL: directory)
        try db.dbQueue.write {
            try $0.execute(sql: "CREATE TRIGGER fail_insert BEFORE INSERT ON clips BEGIN SELECT RAISE(ABORT, 'synthetic test failure'); END")
        }
        for text in ["password=synthetic", "ordinary image"] {
            let snapshot = ClipboardSnapshot(changeCount: 1, typeNames: ["public.png"], fileURLs: [],
                imageData: data, imageTypeName: "public.png", string: text)
            let changed = await ingestor.ingest(snapshot: snapshot, policy: .init(
                appBundleIdentifier: nil, ignoredApps: [], skipSecretLooking: true))
            XCTAssertFalse(changed)
            XCTAssertTrue(try FileManager.default.contentsOfDirectory(atPath: directory.path).isEmpty)
        }
        XCTAssertEqual(try ClipRepository(database: db).count(), 0)
        XCTAssertEqual(try db.dbQueue.read { try Int.fetchOne($0, sql: "SELECT COUNT(*) FROM clips_fts") }, 0)
    }

    func testAdditionalSecretFormatsAndOrdinaryText() {
        let positives = ["sk-proj-" + String(repeating: "a", count: 32),
                         "ASIAIOSFODNN7EXAMPLE", "验证码是 1234", "驗證碼：87654321",
                         "OTP is 12345678", "-----BEGIN PRIVATE KEY-----",
                         "Bearer abcd+/ef~1234=="]
        for sample in positives { XCTAssertTrue(SecretDetector.looksSecret(sample)) }
        for sample in ["订单号 123456", "version 1.2.3", "the bearer of good news", "2026-10-18",
                       "password manager", "code review 123456", "const tokenizer = new Tokenizer()"] {
            XCTAssertFalse(SecretDetector.looksSecret(sample))
        }
    }

    func testWatcherDoesNotDeliverMarkedContentAndCanRestart() {
        let pb = NSPasteboard.withUniqueName()
        defer { pb.releaseGlobally() }
        let watcher = ClipboardWatcher(pasteboard: pb)
        var changes = 0
        watcher.onChange = { _, _ in changes += 1 }
        watcher.start(); watcher.start(); watcher.stop(); watcher.start(); watcher.stop()
        pb.declareTypes([.string, .init("org.nspasteboard.ConcealedType")], owner: nil)
        pb.setString("private", forType: .string)
        XCTAssertFalse(watcher.pollNow())
        XCTAssertEqual(changes, 0)
        pb.clearContents(); pb.setString("public", forType: .string)
        XCTAssertTrue(watcher.pollNow())
        XCTAssertFalse(watcher.pollNow())
        XCTAssertEqual(changes, 1)
    }
}

@MainActor
final class BiometricGateTests: XCTestCase {
    func testFailedAuthenticationStaysLocked() async {
        let auth = FakeOwnerAuthenticator(result: false)
        let gate = BiometricGate(authenticator: auth, enabled: { true })
        let allowed = await gate.authenticateIfNeeded()
        XCTAssertFalse(allowed)
        XCTAssertFalse(gate.isUnlocked)
        XCTAssertEqual(auth.calls, 1)
    }

    func testCancelledTaskCannotUnlockEvenWithSuccessfulAuthenticator() async {
        let auth = FakeOwnerAuthenticator(result: true)
        let gate = BiometricGate(authenticator: auth, enabled: { true })
        let request = Task { @MainActor in await gate.authenticateIfNeeded() }
        request.cancel()
        let allowed = await request.value
        XCTAssertFalse(allowed)
        XCTAssertFalse(gate.isUnlocked)
    }

    func testSuccessfulAuthenticationAndRelockRequireNewPrompt() async {
        let auth = FakeOwnerAuthenticator(result: true)
        let gate = BiometricGate(authenticator: auth, enabled: { true })
        let first = await gate.authenticateIfNeeded()
        let second = await gate.authenticateIfNeeded()
        XCTAssertTrue(first); XCTAssertTrue(second); XCTAssertEqual(auth.calls, 1)
        gate.relock()
        XCTAssertFalse(gate.isUnlocked)
        let third = await gate.authenticateIfNeeded()
        XCTAssertTrue(third); XCTAssertEqual(auth.calls, 2)
    }

    func testRelockDuringAuthenticationRejectsLateSuccess() async {
        let auth = FakeOwnerAuthenticator(result: true)
        let gate = BiometricGate(authenticator: auth, enabled: { true })
        auth.onAuthenticate = { gate.relock() }
        let allowed = await gate.authenticateIfNeeded()
        XCTAssertFalse(allowed); XCTAssertFalse(gate.isUnlocked)
    }

    func testDisabledLockDoesNotPrompt() async {
        let auth = FakeOwnerAuthenticator(result: false)
        let gate = BiometricGate(authenticator: auth, enabled: { false })
        let allowed = await gate.authenticateIfNeeded()
        XCTAssertTrue(allowed); XCTAssertEqual(auth.calls, 0)
    }
}

@MainActor
private final class FakeOwnerAuthenticator: OwnerAuthenticating {
    let result: Bool
    var calls = 0
    var onAuthenticate: (() -> Void)?
    init(result: Bool) { self.result = result }
    func authenticate(reason: String) async -> Bool {
        calls += 1; onAuthenticate?(); return result
    }
    func cancel() {}
}
